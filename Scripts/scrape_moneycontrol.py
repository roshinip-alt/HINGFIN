def parse_posts(
    html: str,
    board_url: str,
    symbol: str
) -> list[dict]:

    soup = BeautifulSoup(
        html,
        "html.parser"
    )

    scrape_moment = datetime.now(
        timezone.utc
    )

    post_containers = soup.select(
        "div[class*='read_list']"
    )

    print(
        f"Found {len(post_containers)} "
        f"candidate post containers."
    )

    records = []

    for i, container in enumerate(
        post_containers
    ):

        # ----------------------------------------------------
        # Extract specific fields
        # ----------------------------------------------------

        user_name_el = container.select_one(
            "div[class*='postItem_user_name']"
        )

        time_icon = container.select_one(
            "span[class*='postItem_icon_time']"
        )

        text_el = container.select_one(
            "div[class*='postItem_text_section']"
        )

        


        author_raw = (
            user_name_el.get_text(
                strip=True
            )
            if user_name_el
            else None
        )


        timestamp_raw = None

        if (
            time_icon
            and time_icon.parent
        ):

            parent_text = (
                time_icon.parent.get_text(
                    " ",
                    strip=True
                )
            )

            timestamp_raw = re.sub(
                r"^schedule\s*",
                "",
                parent_text,
                flags=re.IGNORECASE
            ).strip()

        created_utc_dt = (
            parse_post_timestamp(
                timestamp_raw,
                scrape_moment
            )
            if timestamp_raw
            else None
        )

        created_ist_dt = (
            created_utc_dt + IST_OFFSET
            if created_utc_dt
            else None
        )

        
        text_raw = (
            scrub_pii(
                text_el.get_text(
                    "\n",
                    strip=True
                )
            )
            if text_el
            else None
        )

        # Ignore completely empty blocks
        if not (
            author_raw
            or text_raw
        ):

            continue

        
        author_hash = (
            hash_author(author_raw)
            if author_raw
            else None
        )

        # ----------------------------------------------------
        # Unique post ID
        # ----------------------------------------------------

        url_hash = hashlib.sha1(
            board_url.encode("utf-8")
        ).hexdigest()[:10]

        post_id = (
            f"MC_{symbol}_{url_hash}_{i}_"
            f"{(created_utc_dt or scrape_moment).isoformat()}"
        )

        # ----------------------------------------------------
        # Store record
        # ----------------------------------------------------

        records.append({

            "post_id": post_id,

            "source": (
                f"moneycontrol:{symbol}"
            ),

            "platform_id": post_id,

            "text_raw": text_raw,

            "created_utc": (
                created_utc_dt.isoformat()
                if created_utc_dt
                else None
            ),

            "created_ist": (
                created_ist_dt.isoformat()
                if created_ist_dt
                else None
            ),

            "timestamp_raw": timestamp_raw,

            "author_hash": author_hash,

            "parent_id": None,

            "url": board_url,

            "symbol": symbol,

            "collection_date": (
                scrape_moment
                .date()
                .isoformat()
            )
        })

    return records


def main():

    

    boards = load_board_urls(
        BOARD_URLS_FILE
    )

    print()
    print("=" * 70)

    print(
        f"Loaded {len(boards)} verified "
        f"Moneycontrol board URLs"
    )

    print(
        f"Target: at least "
        f"{MIN_POSTS_PER_BOARD} usable posts "
        f"per board"
    )

    print("=" * 70)

    
    driver = create_driver()

    all_records = []

    board_summary = []

    try:

        # ----------------------------------------------------
        # Scrape every board
        # ----------------------------------------------------

        for board_num, board in enumerate(
            boards,
            start=1
        ):

            board_url = board["url"]

            symbol = (
                board.get("symbol")
                or symbol_from_url(board_url)
            )

            company_name = board.get(
                "company_name"
            )

            print()
            print("=" * 70)

            print(
                f"[{board_num}/{len(boards)}] "
                f"{symbol}"
            )

            if company_name:
                print(
                    f"Company: {company_name}"
                )

            print(board_url)

            print("=" * 70)

            try:

                # ------------------------------------------------
                # Load board
                # ------------------------------------------------

                html = load_board_page(
                    driver,
                    board_url,
                    min_posts=MIN_POSTS_PER_BOARD
                )

                # ------------------------------------------------
                # Parse posts
                # ------------------------------------------------

                records = parse_posts(
                    html,
                    board_url=board_url,
                    symbol=symbol
                )

                collected = len(records)

                # Add to global dataset
                all_records.extend(records)

                # ------------------------------------------------
                # Summary
                # ------------------------------------------------

                board_summary.append({

                    "symbol": symbol,

                    "company_name": company_name,

                    "url": board_url,

                    "posts_collected": collected,

                    "target": MIN_POSTS_PER_BOARD,

                    "target_met": (
                        collected
                        >= MIN_POSTS_PER_BOARD
                    ),

                    "status": (
                        "OK"
                        if collected
                        >= MIN_POSTS_PER_BOARD
                        else "SHORT"
                    )
                })

                if (
                    collected
                    >= MIN_POSTS_PER_BOARD
                ):

                    print(
                        f"✓ {symbol}: "
                        f"collected {collected} "
                        f"usable posts "
                        f"(target "
                        f"{MIN_POSTS_PER_BOARD})"
                    )

                else:

                    print(
                        f"⚠ {symbol}: "
                        f"only {collected} "
                        f"usable posts found "
                        f"(target "
                        f"{MIN_POSTS_PER_BOARD})"
                    )

            except Exception as exc:

                print(
                    f"✗ {symbol}: FAILED — "
                    f"{exc}"
                )

                board_summary.append({

                    "symbol": symbol,

                    "company_name": company_name,

                    "url": board_url,

                    "posts_collected": 0,

                    "target": MIN_POSTS_PER_BOARD,

                    "target_met": False,

                    "status": (
                        f"FAILED: "
                        f"{type(exc).__name__}"
                    )
                })

                # Continue to next company
                continue

    finally:

        driver.quit()

    # --------------------------------------------------------
    # Nothing collected
    # --------------------------------------------------------

    if not all_records:

        print(
            "\nNo posts were collected."
        )

        return

    # ========================================================
    # GLOBAL DEDUPLICATION
    # ========================================================

    df = pd.DataFrame(
        all_records
    )

    before = len(df)

    df = df.drop_duplicates(
        subset=[
            "url",
            "text_raw"
        ],
        keep="first"
    )

    after = len(df)

    # ========================================================
    # SAVE DATASET
    # ========================================================

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    # CSV
    df.to_csv(
        OUTPUT_FILE,
        index=False
    )

    # Parquet
    df.to_parquet(
        PARQUET_FILE,
        index=False
    )

    # ========================================================
    # SAVE BOARD SUMMARY
    # ========================================================

    summary_df = pd.DataFrame(
        board_summary
    )

    summary_file = (
        OUTPUT_DIR
        / "moneycontrol_board_summary.csv"
    )

    summary_df.to_csv(
        summary_file,
        index=False
    )

    # ========================================================
    # FINAL REPORT
    # ========================================================

    print()
    print("=" * 70)
    print("SCRAPE COMPLETE")
    print("=" * 70)

    print(
        f"Total raw records collected: "
        f"{before}"
    )

    print(
        f"After exact deduplication:   "
        f"{after}"
    )

    print(
        f"CSV:     {OUTPUT_FILE}"
    )

    print(
        f"Parquet: {PARQUET_FILE}"
    )

    print(
        f"Summary: {summary_file}"
    )

    # --------------------------------------------------------
    # Board target summary
    # --------------------------------------------------------

    met = int(
        summary_df[
            "target_met"
        ].sum()
    )

    total = len(
        summary_df
    )

    print(
        f"Boards meeting "
        f"{MIN_POSTS_PER_BOARD}-post target: "
        f"{met}/{total}"
    )

    # --------------------------------------------------------
    # Show short boards
    # --------------------------------------------------------

    short_boards = summary_df[
        ~summary_df["target_met"]
    ]

    if not short_boards.empty:

        print()
        print(
            "Boards below target:"
        )

        for _, row in (
            short_boards.iterrows()
        ):

            print(
                f"  - {row['symbol']}: "
                f"{row['posts_collected']} "
                f"/ {row['target']}"
            )


if __name__ == "__main__":
    main()