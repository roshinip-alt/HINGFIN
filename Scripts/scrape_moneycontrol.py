# Absolute timestamp
# ------------------------------------------------------------

_ABSOLUTE_TIME_RE = re.compile(
    r"(\d{1,2}):(\d{2})\s*"
    r"(AM|PM)\s+"
    r"([A-Za-z]{3})\s+"
    r"(\d{1,2})"
    r"(?:st|nd|rd|th)?",
    re.IGNORECASE
)


_MONTH_ABBR_TO_NUM = {

    "jan": 1,
    "feb": 2,
    "mar": 3,
    "apr": 4,
    "may": 5,
    "jun": 6,

    "jul": 7,
    "aug": 8,
    "sep": 9,
    "oct": 10,
    "nov": 11,
    "dec": 12,
}


def parse_absolute_time(
    raw: str,
    reference: datetime
) -> datetime | None:

    if not raw:
        return None

    match = _ABSOLUTE_TIME_RE.search(raw)

    if not match:
        return None

    hour, minute, ampm, month_abbr, day = match.groups()

    month = _MONTH_ABBR_TO_NUM.get(
        month_abbr.lower()
    )

    if month is None:
        return None

    hour = int(hour) % 12

    if ampm.upper() == "PM":
        hour += 12

    year = reference.year

    try:

        candidate_ist_naive = datetime(
            year,
            month,
            int(day),
            hour,
            int(minute)
        )

    except ValueError:

        return None

    reference_ist_naive = (
        reference + IST_OFFSET
    ).replace(tzinfo=None)

    # Handle December → January rollover
    if candidate_ist_naive > reference_ist_naive:

        candidate_ist_naive = (
            candidate_ist_naive
            .replace(year=year - 1)
        )

    candidate_utc = (
        candidate_ist_naive
        .replace(tzinfo=timezone.utc)
        - IST_OFFSET
    )

    return candidate_utc


def parse_post_timestamp(
    raw: str,
    reference: datetime
) -> datetime | None:

    return (
        parse_relative_time(
            raw,
            reference
        )
        or
        parse_absolute_time(
            raw,
            reference
        )
    )


