def load_board_urls(path: Path) -> list[dict]:
    """
    Load Moneycontrol board URLs from board_url_lookup.json.

    Expected JSON structure:

    {
        "ADANIENT": {
            "company_name": "Adani Enterprises Ltd.",
            "symbol": "ADANIENT",
            "isin": "INE423A01024",
            "board_url": "https://...",
            "status": "verified"
        }
    }

    Only entries with:
        status == "verified"
        board_url present

    are loaded for scraping.
    """

    if not path.exists():
        raise FileNotFoundError(
            f"Board URL file not found: {path}"
        )

    data = json.loads(
        path.read_text(encoding="utf-8")
    )

    rows = []

    # --------------------------------------------------------
    # New HINGFIN format:
    #
    # {
    #     "ADANIENT": {
    #         "company_name": "...",
    #         "board_url": "...",
    #         "status": "verified"
    #     }
    # }
    # --------------------------------------------------------

    if isinstance(data, dict):

        for symbol, entry in data.items():

            symbol = str(symbol).strip().upper()

            # New structured format
            if isinstance(entry, dict):

                board_url = entry.get("board_url")
                status = entry.get("status")

                # Only scrape verified boards
                if (
                    status != "verified"
                    or not board_url
                ):
                    print(
                        f"Skipping {symbol}: "
                        f"status={status}"
                    )
                    continue

                rows.append({
                    "symbol": symbol,
                    "url": str(board_url).strip(),
                    "company_name": entry.get(
                        "company_name"
                    ),
                    "isin": entry.get("isin"),
                    "moneycontrol_stock_id": entry.get(
                        "moneycontrol_stock_id"
                    )
                })

            # Backward compatibility with:
            #
            # {
            #     "RELIANCE": "https://..."
            # }
            elif isinstance(entry, str):

                board_url = entry.strip()

                if board_url:

                    rows.append({
                        "symbol": symbol,
                        "url": board_url
                    })

    # --------------------------------------------------------
    # Optional support for JSON list format
    # --------------------------------------------------------

    elif isinstance(data, list):

        for item in data:

            if isinstance(item, str):

                rows.append({
                    "url": item.strip()
                })

            elif isinstance(item, dict):

                board_url = item.get("board_url") or item.get("url")

                if not board_url:
                    continue

                rows.append({
                    "symbol": (
                        str(item.get("symbol")).strip().upper()
                        if item.get("symbol")
                        else None
                    ),
                    "url": str(board_url).strip(),
                    "company_name": item.get("company_name"),
                    "isin": item.get("isin")
                })

    else:

        raise ValueError(
            "board_url_lookup.json must contain "
            "a dictionary or list."
        )

    seen = set()
    unique = []

    for item in rows:

        url = item["url"]

        if url in seen:
            continue

        seen.add(url)
        unique.append(item)

    if not unique:

        raise ValueError(
            f"No verified board URLs found in {path}"
        )

    return unique


