def symbol_from_url(url: str) -> str:
    """
    Best-effort symbol extraction from a Moneycontrol URL.

    Normally this won't be needed because our JSON already
    contains the NSE symbol.
    """

    path = urlparse(url).path.rstrip("/")

    filename = path.rsplit("/", 1)[-1]

    match = re.match(
        r"([a-z0-9_-]+)-\d+\.html?$",
        filename,
        re.IGNORECASE
    )

    if match:

        return (
            match.group(1)
            .split("-")[0]
            .upper()
        )

    token = re.sub(
        r"[^A-Za-z0-9]+",
        "_",
        filename
    ).strip("_")

    return token.upper() or "UNKNOWN"



def load_board_page(
    driver,
    url: str,
    min_posts: int = MIN_POSTS_PER_BOARD
):

    print(f"Opening board: {url}")

    driver.get(url)

    # Wait until at least one post container appears
    WebDriverWait(driver, 20).until(
        EC.presence_of_element_located(
            (
                By.CSS_SELECTOR,
                "div[class*='read_list']"
            )
        )
    )

    previous_count = 0
    stagnant_rounds = 0


    for i in range(MAX_SCROLLS + 1):

        current_count = len(
            driver.find_elements(
                By.CSS_SELECTOR,
                "div[class*='read_list']"
            )
        )

        print(
            f"  Scroll {i}/{MAX_SCROLLS}: "
            f"{current_count} candidate containers loaded"
        )

        # We have enough candidates
        if current_count >= min_posts:

            print(
                f"  Reached at least "
                f"{min_posts} candidate containers."
            )

            break

        # Check whether page stopped growing
        if current_count == previous_count:

            stagnant_rounds += 1

        else:

            stagnant_rounds = 0

        if stagnant_rounds >= 2:

            print(
                "  No new posts loaded; stopping."
            )

            break

        previous_count = current_count

        driver.execute_script(
            "window.scrollTo("
            "0, document.body.scrollHeight"
            ");"
        )

        time.sleep(
            SCROLL_PAUSE_SECONDS
        )

    print("  PAGE TITLE:", driver.title)
    print(
        "  PAGE SOURCE LENGTH:",
        len(driver.page_source)
    )

    return driver.page_source



# PII SCRUBBING
EMAIL_RE = re.compile(
    r"[\w.+-]+@[\w-]+\.[\w.-]+"
)

PHONE_RE = re.compile(
    r"(?<!\d)"
    r"(?:\+?91[-\s]?)?"
    r"[6-9]\d{9}"
    r"(?!\d)"
)

AADHAAR_RE = re.compile(
    r"(?<!\d)"
    r"\d{4}\s?\d{4}\s?\d{4}"
    r"(?!\d)"
)


def scrub_pii(text: str) -> str:

    text = EMAIL_RE.sub(
        "<EMAIL>",
        text
    )

    text = PHONE_RE.sub(
        "<PHONE>",
        text
    )

    text = AADHAAR_RE.sub(
        "<ID>",
        text
    )

    return text


IST_OFFSET = timedelta(
    hours=5,
    minutes=30
)


_UNIT_TO_KWARG = {

    "sec": "seconds",
    "secs": "seconds",
    "second": "seconds",
    "seconds": "seconds",

    "min": "minutes",
    "mins": "minutes",
    "minute": "minutes",
    "minutes": "minutes",

    "hour": "hours",
    "hours": "hours",

    "day": "days",
    "days": "days",

    "week": "weeks",
    "weeks": "weeks",
}


_RELATIVE_CHUNK_RE = re.compile(
    r"(\d+)\s*"
    r"(sec|secs|min|mins|hour|hours|"
    r"day|days|week|weeks)",
    re.IGNORECASE
)


def parse_relative_time(
    raw: str,
    reference: datetime
) -> datetime | None:

    if not raw:
        return None

    kwargs = {}

    for amount, unit in _RELATIVE_CHUNK_RE.findall(raw):

        key = _UNIT_TO_KWARG.get(
            unit.lower()
        )

        if key:

            kwargs[key] = (
                kwargs.get(key, 0)
                + int(amount)
            )

    if not kwargs:
        return None

    return reference - timedelta(
        **kwargs
    )


