def hash_author(author: str) -> str | None:
    """
    Hash the author identifier at collection time.

    Cleartext usernames are never stored in the dataset.
    """

    if not author:
        return None

    value = author + AUTHOR_SALT

    return hashlib.sha256(
        value.encode("utf-8")
    ).hexdigest()


